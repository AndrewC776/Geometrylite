import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const names=['engine.mjs','audio.mjs','render.mjs','styles.mjs','view.mjs','game.mjs'];
const chunks=names.map(name=>`\n// ---- ${name} ----\n`+readFileSync(resolve(root,'src',name),'utf8').replace(/^import .*;\s*$/gm,'').replace(/^export /gm,''));
const script=`/* GeometryLite Native 1.0.0 - original source; generated by tools/build.mjs. */\n(()=>{'use strict';\n${chunks.join('\n')}\nglobalThis.GeometryLiteNative={mount,version:VERSION,renderAudioPreview,makeLevel,verifyLevel,previewInput,World};\n})();\n`;
mkdirSync(resolve(root,'dist'),{recursive:true});writeFileSync(resolve(root,'dist/game.js'),script);
const html=readFileSync(resolve(root,'index.html'),'utf8').replace('<script type="module" src="./src/game.mjs"></script>',`<script>${script.replace(/<\/script/gi,'<\\/script')}</script>`);
writeFileSync(resolve(root,'dist/index.html'),html);
console.log(`Built self-contained HTML: ${Buffer.byteLength(html)} bytes; no external assets.`);
